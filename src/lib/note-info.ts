// Claves de la más larga a la más corta, para que "palo de rosa" gane sobre "rosa".
const keys = Object.keys(info).sort((a, b) => b.length - a.length);

// La frase de una nota, o null si no tenemos nada que decir de ella.
export function noteInfo(note: string): string | null {
  const text = ` ${note.toLowerCase().replace(/™/g, "").trim()} `;
  const key = keys.find((candidate) => text.includes(` ${candidate} `));
  return key ? info[key] : null;
}
